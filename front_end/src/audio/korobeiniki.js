// 마디마다 근음을 8분음표로 한 옥타브씩 오르내리는 베이스
const BASS_ROOTS = ['E', 'A', 'E', 'A', 'D', 'C', 'E', 'A'];

export const BASS = BASS_ROOTS.flatMap((root) =>
  Array.from({ length: 8 }, (_, i) => [`${root}${i % 2 === 0 ? 2 : 3}`, 0.5]),
);

export const BASE_TEMPO = 140;
export const MAX_TEMPO = 200;

// 레벨이 오를수록 음악도 조금씩 빨라진다.
export function getMusicTempo(level) {
  return Math.min(MAX_TEMPO, BASE_TEMPO + (level - 1) * 6);
}
